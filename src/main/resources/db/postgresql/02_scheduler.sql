-- =========================================================
-- 3. 분석 모델 필드 매핑
-- =========================================================

CREATE TABLE sched_analysis_model_field (
    analysis_field_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_model_version_id BIGINT NOT NULL,
    target_column VARCHAR(100) NOT NULL,
    source_fields JSONB NOT NULL,
    convert_type VARCHAR(30) NOT NULL DEFAULT 'DIRECT',
    convert_format VARCHAR(100),
    required_yn CHAR(1) NOT NULL DEFAULT 'N',
    sort_order INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_analysis_model_field_version
        FOREIGN KEY (analysis_model_version_id)
        REFERENCES sched_analysis_model_version (analysis_model_version_id),

    CONSTRAINT uq_analysis_model_field_column
        UNIQUE (analysis_model_version_id, target_column),

    CONSTRAINT ck_analysis_model_field_sources
        CHECK (
            jsonb_typeof(source_fields) = 'array'
            AND jsonb_array_length(source_fields) > 0
        ),

    CONSTRAINT ck_analysis_model_field_convert
        CHECK (
            convert_type IN (
                'DIRECT',
                'NUMBER_NORMALIZE',
                'DATE_PARSE',
                'DATE_PARTS'
            )
        ),

    CONSTRAINT ck_analysis_model_field_required
        CHECK (required_yn IN ('Y', 'N')),

    CONSTRAINT ck_analysis_model_field_sort
        CHECK (sort_order >= 0)
);

CREATE INDEX idx_analysis_model_field_version_sort
    ON sched_analysis_model_field (analysis_model_version_id, sort_order);

COMMENT ON TABLE sched_analysis_model_field
IS '가공 결과 JSONB 필드와 분석 테이블 컬럼 간 매핑 설정';

COMMENT ON COLUMN sched_analysis_model_field.analysis_field_id
IS '분석 필드 매핑 식별자';

COMMENT ON COLUMN sched_analysis_model_field.analysis_model_version_id
IS '필드 매핑이 속한 분석 모델 버전 식별자';

COMMENT ON COLUMN sched_analysis_model_field.target_column
IS '분석 데이터를 저장할 대상 DB 컬럼명';

COMMENT ON COLUMN sched_analysis_model_field.source_fields
IS '가공 결과 JSONB에서 읽을 원본 필드명 배열. 예: ["dealYear","dealMonth","dealDay"]';

COMMENT ON COLUMN sched_analysis_model_field.convert_type
IS '데이터 변환 유형(DIRECT: 그대로 저장, NUMBER_NORMALIZE: 숫자 정규화, DATE_PARSE: 날짜 문자열 변환, DATE_PARTS: 날짜 구성 요소 결합)';

COMMENT ON COLUMN sched_analysis_model_field.convert_format
IS '데이터 변환에 사용할 입력 형식. 예: yy.MM.dd';

COMMENT ON COLUMN sched_analysis_model_field.required_yn
IS '필드 매핑 시 값 필수 여부(Y: 필수, N: 선택)';

COMMENT ON COLUMN sched_analysis_model_field.sort_order
IS '분석 필드 매핑 화면 표시 순서';


-- =========================================================
-- 4. 분석 데이터 적재 대상 및 상태 관리
-- =========================================================

CREATE TABLE sched_analysis_load_source (
    analysis_load_source_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_model_version_id BIGINT NOT NULL,
    raw_data_id BIGINT NOT NULL,
    transform_result_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempt_count INTEGER NOT NULL DEFAULT 0,
    loaded_count INTEGER NOT NULL DEFAULT 0,
    error_message VARCHAR(2000),
    started_at TIMESTAMP(6),
    finished_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_analysis_load_source_version
        FOREIGN KEY (analysis_model_version_id)
        REFERENCES sched_analysis_model_version (analysis_model_version_id),

    CONSTRAINT fk_analysis_load_source_raw
        FOREIGN KEY (raw_data_id)
        REFERENCES sched_collect_raw_data (raw_data_id),

    CONSTRAINT fk_analysis_load_source_result
        FOREIGN KEY (transform_result_id)
        REFERENCES sched_transform_result (transform_result_id),

    -- 동일 분석 모델 버전에서는 Raw Data를 중복 적재하지 않는다.
    CONSTRAINT uq_analysis_load_source_model_raw
        UNIQUE (analysis_model_version_id, raw_data_id),

    CONSTRAINT ck_analysis_load_source_status
        CHECK (status IN ('PENDING', 'RUNNING', 'SUCCESS', 'FAILED')),

    CONSTRAINT ck_analysis_load_source_attempt
        CHECK (attempt_count >= 0),

    CONSTRAINT ck_analysis_load_source_count
        CHECK (loaded_count >= 0),

    -- 성공한 적재 작업에는 사용한 가공 결과가 반드시 존재해야 한다.
    CONSTRAINT ck_analysis_load_source_success_result
        CHECK (
            status <> 'SUCCESS'
            OR transform_result_id IS NOT NULL
        )
);

-- 대기 중인 적재 작업 조회 및 선점을 위한 인덱스
CREATE INDEX idx_analysis_load_source_pending
    ON sched_analysis_load_source (
