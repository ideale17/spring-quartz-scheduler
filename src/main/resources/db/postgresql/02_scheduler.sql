-- =========================================================
-- 10. Raw Data 비동기 가공 작업 및 실행 이력
-- =========================================================

CREATE TABLE sched_transform_task (
    transform_task_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_data_id BIGINT NOT NULL,
    transform_rule_version_id BIGINT NOT NULL,
    request_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempt_count INTEGER NOT NULL DEFAULT 0,
    started_at TIMESTAMP(6),
    finished_at TIMESTAMP(6),
    error_message VARCHAR(2000),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_transform_task_raw_data
        FOREIGN KEY (raw_data_id)
        REFERENCES sched_collect_raw_data (raw_data_id),

    CONSTRAINT fk_transform_task_rule_version
        FOREIGN KEY (transform_rule_version_id)
        REFERENCES sched_transform_rule_version (transform_rule_version_id),

    CONSTRAINT ck_transform_task_request_type
    	CHECK (request_type IN ('SCHEDULED', 'MANUAL')),

    CONSTRAINT ck_transform_task_status
        CHECK (status IN ('PENDING', 'RUNNING', 'SUCCESS', 'FAILED')),

    CONSTRAINT ck_transform_task_attempt_count
        CHECK (attempt_count >= 0)
);

COMMENT ON TABLE sched_transform_task
IS 'Raw Data 비동기 가공 작업 및 실행 이력';

COMMENT ON COLUMN sched_transform_task.transform_task_id
IS '가공 작업 식별자';

COMMENT ON COLUMN sched_transform_task.raw_data_id
IS '가공 대상 원본 데이터 식별자';

COMMENT ON COLUMN sched_transform_task.transform_rule_version_id
IS '가공 작업 등록 시 확정한 규칙 버전 식별자';

COMMENT ON COLUMN sched_transform_task.request_type
IS '가공 작업 요청 유형(SCHEDULED, MANUAL)';

COMMENT ON COLUMN sched_transform_task.status
IS '가공 작업 상태(PENDING, RUNNING, SUCCESS, FAILED)';

COMMENT ON COLUMN sched_transform_task.attempt_count
IS '가공 작업 처리 시도 횟수';

COMMENT ON COLUMN sched_transform_task.started_at
IS '가공 작업 시작 일시';

COMMENT ON COLUMN sched_transform_task.finished_at
IS '가공 작업 종료 일시';

COMMENT ON COLUMN sched_transform_task.error_message
IS '가공 작업 실패 원인';

COMMENT ON COLUMN sched_transform_task.created_at
IS '가공 작업 등록 일시';

COMMENT ON COLUMN sched_transform_task.updated_at
IS '가공 작업 상태 변경 일시';


-- 가공 Worker의 대기 작업 조회
CREATE INDEX idx_transform_task_pending
    ON sched_transform_task (created_at, transform_task_id)
    WHERE status = 'PENDING';

-- 원본 데이터별 가공 이력 조회
CREATE INDEX idx_transform_task_raw_data
    ON sched_transform_task (
        raw_data_id,
        transform_rule_version_id,
        created_at DESC
    );

-- 예약 가공 작업 중복 등록 방지
CREATE UNIQUE INDEX uq_transform_task_scheduled
    ON sched_transform_task (
        raw_data_id,
        transform_rule_version_id
    )
    WHERE request_type = 'SCHEDULED'
      AND status IN ('PENDING', 'RUNNING', 'SUCCESS');


