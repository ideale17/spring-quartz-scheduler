    )
    WHERE status = 'PENDING';

CREATE INDEX idx_analysis_load_source_raw
    ON sched_analysis_load_source (raw_data_id);

CREATE INDEX idx_analysis_load_source_result
    ON sched_analysis_load_source (transform_result_id);

