-- =========================================================
-- Data Loading
-- 분석 모델 및 관계형 데이터 적재
--
-- PostgreSQL
-- 신규 공통 테이블 4개 + 부동산 분석 테이블 1개
--
-- 기존 Transform 테이블은 변경하지 않는다.
-- 테이블 생성 순서: 모델 → 버전 → 필드 → 적재 → 업무 데이터
-- =========================================================

-- =========================================================
-- 1. 분석 모델 기본 정보
-- =========================================================

CREATE TABLE sched_analysis_model (
    analysis_model_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    target_schema VARCHAR(100) NOT NULL DEFAULT 'public',
    target_table VARCHAR(100) NOT NULL,
    enabled CHAR(1) NOT NULL DEFAULT 'Y',
    current_version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_analysis_model_name
        UNIQUE (model_name),

    CONSTRAINT uq_analysis_model_target
        UNIQUE (target_schema, target_table),

    CONSTRAINT ck_analysis_model_enabled
        CHECK (enabled IN ('Y', 'N')),

    CONSTRAINT ck_analysis_model_version
        CHECK (current_version >= 1)
);

COMMENT ON TABLE sched_analysis_model
IS '분석 모델 기본 정보 및 분석 데이터 적재 대상 테이블 관리';

COMMENT ON COLUMN sched_analysis_model.analysis_model_id
IS '분석 모델 식별자';

COMMENT ON COLUMN sched_analysis_model.model_name
IS '분석 모델명';

COMMENT ON COLUMN sched_analysis_model.description
IS '분석 모델 설명';

COMMENT ON COLUMN sched_analysis_model.target_schema
IS '분석 데이터가 저장될 DB 스키마명';

COMMENT ON COLUMN sched_analysis_model.target_table
IS '분석 데이터가 저장될 대상 테이블명';

COMMENT ON COLUMN sched_analysis_model.enabled
IS '분석 모델 사용 여부(Y: 사용, N: 미사용)';

COMMENT ON COLUMN sched_analysis_model.current_version
IS '현재 사용 중인 분석 모델 버전 번호';

COMMENT ON COLUMN sched_analysis_model.created_at
IS '분석 모델 등록 일시';

